/**
 * Build-time: writes generated env files from process.env and optional frontend/.env.
 *
 * Outputs:
 *   - environment.production.ts — used when Angular replaces environment.ts (prod builds).
 *   - environment.defaults.ts — imported by environment.ts so `ng serve` respects .env.
 *
 * Variables (first match wins):
 *   AUDITIQ_API_BASE_URL, NG_APP_API_BASE_URL  (dev / ng serve)
 *   AUDITIQ_WS_BASE_URL, NG_APP_WS_BASE_URL  (optional; derived from API URL when possible)
 *   AUDITIQ_API_BASE_URL_PRODUCTION, NG_APP_API_BASE_URL_PRODUCTION  (override prod API URL)
 *   AUDITIQ_WS_BASE_URL_PRODUCTION, NG_APP_WS_BASE_URL_PRODUCTION  (override prod WebSocket origin)
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.resolve(__dirname, '..');
const envPath = path.join(frontendRoot, '.env');
const outProd = path.join(frontendRoot, 'src', 'environments', 'environment.production.ts');
const outDefaults = path.join(frontendRoot, 'src', 'environments', 'environment.defaults.ts');

const LOCAL_DEV_API = 'http://localhost:8000/api';
const LOCAL_DEV_WS = 'ws://localhost:8000';

/**
 * API prod : FastAPI exposée via Netlify Functions + Mangum (handler netlify/functions/auditiq).
 * URL du site API Netlify (ajuster si besoin via AUDITIQ_API_BASE_URL_PRODUCTION).
 */
const DEFAULT_PROD_API = 'https://auditiq-back.vercel.app/api';
const DEFAULT_PROD_WS = 'wss://auditiq-back.vercel.app';

function loadDotEnv(file) {
  if (!fs.existsSync(file)) return;
  const text = fs.readFileSync(file, 'utf8');
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq < 1) continue;
    const key = trimmed.slice(0, eq).trim();
    let val = trimmed.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = val;
  }
}

function pick(...keys) {
  for (const k of keys) {
    const v = process.env[k];
    if (v !== undefined && String(v).trim() !== '') return String(v).trim();
  }
  return '';
}

/** When API is absolute HTTPS, default WS origin (path /ws/... is appended in the app). */
function deriveWsFromApi(apiBaseUrl) {
  if (!apiBaseUrl || apiBaseUrl.startsWith('/')) return '';
  try {
    const u = new URL(apiBaseUrl);
    const wsProto = u.protocol === 'https:' ? 'wss:' : 'ws:';
    return `${wsProto}//${u.host}`;
  } catch {
    return '';
  }
}

loadDotEnv(envPath);

const apiRaw = pick('AUDITIQ_API_BASE_URL', 'NG_APP_API_BASE_URL');

/**
 * Production bundle: dedicated prod URL (separate Netlify site for API).
 * Override with AUDITIQ_API_BASE_URL_PRODUCTION / NG_APP_API_BASE_URL_PRODUCTION at build time if needed.
 */
const apiProd =
  pick('AUDITIQ_API_BASE_URL_PRODUCTION', 'NG_APP_API_BASE_URL_PRODUCTION') || DEFAULT_PROD_API;
let wsProd = pick('AUDITIQ_WS_BASE_URL_PRODUCTION', 'NG_APP_WS_BASE_URL_PRODUCTION');
if (!wsProd) wsProd = deriveWsFromApi(apiProd) || DEFAULT_PROD_WS;

/**
 * Dev server (`ng serve`): relative /api hits the Angular dev host, not FastAPI.
 * If the value is relative or empty, point at the local backend instead.
 */
function resolveApiForDevDefaults() {
  if (!apiRaw) return LOCAL_DEV_API;
  if (apiRaw.startsWith('/')) return LOCAL_DEV_API;
  return apiRaw;
}

const apiDev = resolveApiForDevDefaults();
let wsDev = pick('AUDITIQ_WS_BASE_URL', 'NG_APP_WS_BASE_URL');
if (!wsDev) wsDev = deriveWsFromApi(apiDev);
if (!wsDev) wsDev = LOCAL_DEV_WS;

const prodContent = `/* eslint-disable */
// Generated by scripts/generate-environment.mjs — do not edit by hand.
export const environment = {
  production: true,
  apiBaseUrl: ${JSON.stringify(apiProd)},
  wsBaseUrl: ${JSON.stringify(wsProd)},
};
`;

const defaultsContent = `/* eslint-disable */
// Generated by scripts/generate-environment.mjs — do not edit by hand.
/** Values for non-production builds (imported from environment.ts). */
export const devEnvironment = {
  apiBaseUrl: ${JSON.stringify(apiDev)},
  wsBaseUrl: ${JSON.stringify(wsDev)},
};
`;

const envDir = path.dirname(outProd);
fs.mkdirSync(envDir, { recursive: true });
fs.writeFileSync(outProd, prodContent, 'utf8');
fs.writeFileSync(outDefaults, defaultsContent, 'utf8');
console.log('[generate-environment] Wrote', path.relative(frontendRoot, outProd));
console.log('[generate-environment] Wrote', path.relative(frontendRoot, outDefaults));
console.log(
  '[generate-environment] production api=',
  apiProd,
  'ws=',
  wsProd || '(empty → same-origin at runtime)',
);
console.log('[generate-environment] development api=', apiDev, 'ws=', wsDev);
